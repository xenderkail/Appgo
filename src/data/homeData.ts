// Helper function to create infinite or custom live channels
export function generateLiveChannel(
  index: number,
  genre?: string,
  customName?: string
): LiveChannel {
  const genresList: Exclude<LiveGenre, 'All'>[] = [
    'News',
    'Sports',
    'Entertainment',
    'Gaming',
    'Science & Nature',
    'Music & Lo-Fi',
    'Tech',
  ];
  const selectedGenre = (genre && genre !== 'All' ? genre : genresList[index % genresList.length]) as Exclude<LiveGenre, 'All'>;
  const channelNum = index + 1;
  const sampleVideos = [
    'https://filesamples.com/samples/video/mp4/sample_640x360.mp4',
    'https://vjs.zencdn.net/v/oceans.mp4',
    'https://interactive-examples.mdn.mozilla.net/media/cc0-videos/flower.mp4',
    'https://filesamples.com/samples/video/mp4/sample_960x400_ocean_with_audio.mp4',
    'https://filesamples.com/samples/video/mp4/sample_960x540.mp4',
    'https://filesamples.com/samples/video/mp4/sample_1280x720.mp4',
    'https://filesamples.com/samples/video/mp4/sample_960x540.mp4',
  ];

  return {
    id: `custom-channel-${channelNum}-${Date.now()}`,
    name: customName || `Live Stream Channel #${channelNum}`,
    tagline: `24/7 High-Definition ${selectedGenre} Broadcast`,
    genre: selectedGenre,
    logo: `https://images.unsplash.com/photo-1518709268805-4e9042af9f23?auto=format&fit=crop&w=150&q=80`,
    currentProgram: `Live Program: Episode ${channelNum} on Air`,
    description: `Real-time multi-angle streaming broadcast in crystal-clear definition.`,
    viewers: `${(Math.random() * 40 + 10).toFixed(1)}K`,
    viewersCount: Math.floor(Math.random() * 40000 + 10000),
    resolution: channelNum % 2 === 0 ? '4K' : '1080p 60',
    streamUrl: sampleVideos[index % sampleVideos.length],
    channelUrl: 'https://appgo.dev',
    posterUrl: `https://images.unsplash.com/photo-1517649763962-0c623266ddc0?auto=format&fit=crop&w=800&q=80`,
    country: 'Global',
    language: 'English',
  };
}

